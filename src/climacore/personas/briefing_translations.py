def get_localized_persona_title(persona_id: str, language: str = "en") -> str:
    """Retrieve localized title for persona, falling back to English."""
    norm = persona_id.lower().replace("-", "_")
    canonical = PERSONA_ALIASES.get(norm, norm)
    lang = (language or "en").strip().lower()
    if lang not in SUPPORTED_LANGUAGES:
        lang = "en"

    p_dict = PERSONA_TITLES_I18N.get(canonical)
    if p_dict and lang in p_dict:
        return p_dict[lang]
    if p_dict and "en" in p_dict:
        return p_dict["en"]
    return persona_id.replace("_", " ").title()


def get_localized_briefing_content(
    persona_id: str,
    condition: str,
    language: str = "en"
) -> Tuple[str, List[str]]:
    """
    Retrieve localized operational guidance and advisories list.
    condition: 'extreme_hot', 'hot', 'rainy', or 'default'
    language: 'en', 'hi', 'bn', 'ta', 'te', 'mr', 'gu'
    """
    norm = persona_id.lower().replace("-", "_")
    canonical = PERSONA_ALIASES.get(norm, norm)
    lang = (language or "en").strip().lower()
    if lang not in SUPPORTED_LANGUAGES:
        lang = "en"

    # Try specific persona catalog
    if canonical in BRIEFING_CATALOG:
        cond_dict = BRIEFING_CATALOG[canonical].get(condition) or BRIEFING_CATALOG[canonical].get("default")
        if cond_dict:
            if lang in cond_dict:
                return cond_dict[lang]
            if "en" in cond_dict:
                return cond_dict["en"]

    # Try generic catalog
    fallback = GENERIC_BRIEFINGS.get(lang) or GENERIC_BRIEFINGS["en"]
    return fallback["guidance"], fallback["advisories"]
